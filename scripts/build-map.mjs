// Builds src/content/caba.ts: the outline and the barrios of the Ciudad de Buenos Aires as SVG paths, so the page draws
// its own map (one ink, no tiles, no requests at visit time). Source: the "Barrios" GeoJSON of the city's open data
// (Buenos Aires Data, CC BY 4.0). Run `node scripts/build-map.mjs [file or URL]` only when the source changes.
import { readFile, writeFile } from 'node:fs/promises';

const source = process.argv[2] || 'https://cdn.buenosaires.gob.ar/datosabiertos/datasets/ministerio-de-educacion/barrios/barrios.geojson';
const text = source.startsWith('http') ? await (await fetch(source)).text() : await readFile(source, 'utf8');
const { features } = JSON.parse(text);

// Equirectangular projection around the city, in degrees: enough for a schematic map.
const lat0 = -34.6, lon0 = -58.45, k = Math.cos(lat0 * Math.PI / 180);
const project = ([lon, lat]) => [(lon - lon0) * k, -(lat - lat0)];
const key = point => point.map(value => value.toFixed(7)).join(',');

const rings = feature => (feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates)
  .flatMap(polygon => polygon.map(ring => ring.map(project)));
const barrios = features.map(feature => ({ nombre: String(feature.properties.nombre ?? feature.properties.BARRIO ?? '').trim(), rings: rings(feature) }))
  .filter(barrio => barrio.nombre).sort((a, b) => a.nombre.localeCompare(b.nombre, 'es'));

// Douglas-Peucker on a closed ring; the tolerance is in projected degrees (0.0004 ≈ 45 m).
function simplify(points, tolerance) {
  const distance = (p, a, b) => {
    const dx = b[0] - a[0], dy = b[1] - a[1];
    if (dx === 0 && dy === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
    const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy)));
    return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
  };
  const keep = new Array(points.length).fill(false); keep[0] = keep[points.length - 1] = true;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [start, end] = stack.pop();
    let farthest = 0, index = -1;
    for (let i = start + 1; i < end; i++) { const d = distance(points[i], points[start], points[end]); if (d > farthest) { farthest = d; index = i; } }
    if (index !== -1 && farthest > tolerance) { keep[index] = true; stack.push([start, index], [index, end]); }
  }
  return points.filter((_, i) => keep[i]);
}

// The city outline: the edges that belong to exactly one barrio, chained into rings.
const edges = new Map();
for (const { rings: barrioRings } of barrios) for (const ring of barrioRings) for (let i = 0; i < ring.length - 1; i++) {
  const a = key(ring[i]), b = key(ring[i + 1]); if (a === b) continue;
  const edge = a < b ? `${a}|${b}` : `${b}|${a}`;
  edges.set(edge, (edges.get(edge) || 0) + 1);
}
const next = new Map();
for (const [edge, count] of edges) if (count === 1) { const [a, b] = edge.split('|'); (next.get(a) || next.set(a, []).get(a)).push(b); (next.get(b) || next.set(b, []).get(b)).push(a); }
const outlines = []; const visited = new Set();
for (const start of next.keys()) {
  if (visited.has(start)) continue;
  const chain = [start]; visited.add(start); let current = start;
  for (;;) { const candidate = (next.get(current) || []).find(point => !visited.has(point)); if (!candidate) break; visited.add(candidate); chain.push(candidate); current = candidate; }
  if (chain.length > 2) outlines.push(chain.map(point => point.split(',').map(Number)));
}
outlines.sort((a, b) => b.length - a.length);
if (!outlines.length) throw new Error('No se pudo trazar el contorno de la ciudad: las parcelas no comparten vértices.');

const tolerance = 0.0004;
const simplifiedBarrios = barrios.map(({ nombre, rings: barrioRings }) => ({ nombre, rings: barrioRings.map(ring => simplify(ring, tolerance)) }));
const outline = simplify([...outlines[0], outlines[0][0]], tolerance);
const everyPoint = simplifiedBarrios.flatMap(barrio => barrio.rings.flat());
const minX = Math.min(...everyPoint.map(p => p[0])), maxX = Math.max(...everyPoint.map(p => p[0]));
const minY = Math.min(...everyPoint.map(p => p[1])), maxY = Math.max(...everyPoint.map(p => p[1]));
const width = 1000, scale = width / (maxX - minX), height = Math.round((maxY - minY) * scale);
const toPath = ring => 'M' + ring.map(([x, y]) => `${((x - minX) * scale).toFixed(1)} ${((y - minY) * scale).toFixed(1)}`).join('L') + 'Z';

const content = `/** Generated by scripts/build-map.mjs from the "Barrios" GeoJSON of Buenos Aires Data (CC BY 4.0). Do not edit by hand. */
export const caba = {
  width: ${width},
  height: ${height},
  /** Equirectangular projection used by projectCaba, in degrees. */
  lat0: ${lat0},
  lon0: ${lon0},
  k: ${k},
  minX: ${minX},
  minY: ${minY},
  scale: ${scale},
  outline: "${toPath(outline)}",
  barrios: [
${simplifiedBarrios.map(({ nombre, rings: barrioRings }) => `    { nombre: ${JSON.stringify(nombre)}, d: "${barrioRings.map(toPath).join('')}" },`).join('\n')}
  ],
};

/** Map coordinates (viewBox units) of a latitude and longitude. */
export function projectCaba(lat: number, lon: number) {
  return { x: ((lon - caba.lon0) * caba.k - caba.minX) * caba.scale, y: (-(lat - caba.lat0) - caba.minY) * caba.scale };
}
`;
await writeFile(new URL('../src/content/caba.ts', import.meta.url), content);
console.log(`Mapa listo: ${simplifiedBarrios.length} barrios, contorno de ${outline.length} puntos (${outlines.length} anillos), ${Math.round(content.length / 1024)} KB.`);
